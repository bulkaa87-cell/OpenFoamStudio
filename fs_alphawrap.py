"""Обгортання геометрії алгоритмом CGAL Alpha Wrapping — через `wrapwrap.exe`.

Навіщо окремим модулем, а не в `fs_geometry`: причина та сама, що й у
`fs_winfix` — це не наш алгоритм, а виклик чужої програми. Її може не бути на
цій машині, вона йде хвилинами й говорить своїм текстом у stdout; нічому з
цього не місце в геометрії.

ЩО ЦЕ. `CGAL::alpha_wrap_3` — пакет 3D Alpha Wrapping із CGAL (з 5.5, 2022).
Бере на вхід сітку, трикутний суп АБО хмару точок і будує поверхню, яка
строго охоплює вхід і гарантовано замкнена, без самоперетинів і 2-manifold.
Гарантія тут математична, а не «здебільшого виходить»: саме тому це надійний
крайній засіб, коли вхід — суцільне сміття. Ми кличемо готову збірку
`wrapwrap` (github.com/ipadjen/wrapwrap), бо сам CGAL — це C++ з Boost і GMP,
і тягнути тулчейн у програму на PySide6 не варто.

ЧИМ КРАЩИЙ ЗА НАШ `voxel_wrap`. Обидва дають замкнену оболонку, але воксель
ріже все по осях сітки: кромка під кутом стає драбинкою, і дрібне зникає
цілком. Alpha wrap веде поверхню по самій геометрії, тому кромки лишаються
кромками. Ціна — не в памʼяті (воксельна сітка на 60 млн вузлів там реальна
межа), а в часі.

ЧИМ ГІРШИЙ ЗА `winfix`. Це НЕ ремонт: модель не лагодиться, а перерізається
наново — геометрія змінюється всюди, а не там, де була дірка. Якщо служба
Windows справляється, вона краща. Alpha wrap — коли не справляється ніхто.

ОБМІН ІДЕ ЧЕРЕЗ STL: `wrapwrap` читає й пише файли (STL, OBJ, PLY, OFF),
свого API немає. STL зберігає float32 і НЕ зберігає спільних вершин — після
читання обовʼязково зшиваємо (`clean`), інакше сітка виглядає правильно, а за
топологією розсипана на окремі трикутники, і діагностика покаже non-manifold
на кожному ребрі.

ОДИНИЦІ. Сітки в програмі — у метрах. Самі параметри (alpha, offset) у
`wrapwrap` ВІДНОСНІ — вимірюються в частках діагоналі габариту, і на масштаб
не зважають: перевірено на тому самому кубі 10 мм і 200 мм — та сама кількість
трикутників (696 648 проти 696 9xx при alpha=500). А от координати все одно
переводимо в міліметри, як і для служби Windows: це інструменти для друку й
CAD, і всі їхні внутрішні допуски розраховані на цей масштаб.

ОБА ЧИСЛА — ДІЛЬНИКИ, І ЦЕ ГОЛОВНА ПАСТКА. Абсолютний розмір = діагональ
поділити на число, тож БІЛЬШЕ число означає МЕНШИЙ розмір. Людині такі числа
показувати не можна: вікно питає міліметри й переводить саме (`relative_for_mm`).

OFFSET — ЦЕ РІВНО ТЕ, НА СКІЛЬКИ ТІЛО ВИРОСТЕ. Виміряно на кубі 10 мм
(діагональ 17.32 мм, alpha=100): відхилення обгортки від вихідної поверхні
збігається з діагональ/offset до третьої цифри, і медіана з максимумом — те
саме число, тобто зсув рівномірний:

    offset=25   зазор 0.693 мм   габарит 11.399   відхилення 0.693 (макс 0.700)
    offset=150  зазор 0.115 мм   габарит 10.233   відхилення 0.115 (макс 0.117)
    offset=2000 зазор 0.009 мм   габарит 10.017   відхилення 0.009 (макс 0.009)
    offset=5000 зазор 0.003 мм   габарит 10.007   відхилення 0.003 (макс 0.003)

Тобто «максимально близько до оригіналу» = якнайменший зазор; ціна мала —
трикутників при offset=5000 вийшло 52 тис. проти 28 тис. при 150, час той
самий. Нуль ставити не можна: оболонка мусить строго охоплювати вхід.

ALPHA — ЦЕ РАДІУС КУЛІ, ЯКА МУСИТЬ ПРОЛІЗТИ. Не «точність» узагалі: на зсув
поверхні вона не впливає ніяк (при фіксованому offset=2000 відхилення лишалося
0.009 мм і при alpha=20, і при alpha=300 — мінялася лише кількість трикутників,
3 тис. проти 278 тис.). Вона вирішує інше: все, вужче за кулю, обгортка
перекриває зверху. Виміряно на двох блоках 10 мм зі щілиною 1 мм:

    alpha=10   куля 2.53 мм   щілина залита повністю
    alpha=25   куля 1.01 мм   щілина залита повністю
    alpha=50   куля 0.51 мм   щілина відкрита (залито 28% обʼєму)
    alpha=100  куля 0.25 мм   щілина відкрита (15%)

Тобто куля мусить бути вдвічі-вчетверо менша за найвужчу щілину, яку треба
зберегти. Трикутників від alpha — у квадраті, тому ставити її дрібнішою за
потрібне означає лише чекати.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np
import pyvista as pv

EXE_NAME = "wrapwrap.exe" if sys.platform == "win32" else "wrapwrap"

M_TO_MM = 1000.0

# Прогрес `wrapwrap` — це рядки через \r, тисячі за секунду («cells to visit:
# N»). Гнати кожен у вікно означало б завалити чергу подій Qt задарма.
_SAY_EVERY = 0.4

# Не своє вікно: дочірній процес у GUI-програмі інакше блимає консоллю.
_NO_WINDOW = 0x08000000 if sys.platform == "win32" else 0


def exe_path() -> Path | None:
    """Де лежить `wrapwrap`, або None.

    Спершу поруч із програмою (`tools/`), потім у PATH: свою збірку тримаємо
    в теці, але не змушуємо — хто поставив системно, теж працює.
    """
    local = Path(__file__).parent / "tools" / EXE_NAME
    if local.is_file():
        return local
    found = shutil.which(EXE_NAME)
    return Path(found) if found else None


def available() -> bool:
    return exe_path() is not None


def why_not() -> str:
    """Чому кнопка неактивна — людськими словами."""
    return ("Немає " + EXE_NAME + " — це окрема програма, збірка CGAL Alpha "
            "Wrapping." + "\n\n"
            "Завантажити: github.com/ipadjen/wrapwrap (розділ Releases, "
            "готовий " + EXE_NAME + " для Windows, ~1.3 МБ) і покласти у "
            "теку:" + "\n\n"
            "    " + str(Path(__file__).parent / "tools") + "\n\n"
            "Ремонт службою Windows («Полагодити як слайсер») і воксельне "
            "«Обгорнути…» працюють і без цього.")


# --------------------------------------------------------------------------
# STL туди й назад
# --------------------------------------------------------------------------

def _to_stl(mesh: pv.PolyData, path: Path) -> int:
    """Сітка в метрах → файл STL у міліметрах. Повертає кількість трикутників."""
    out = mesh.triangulate()
    # Копія НЕ зайва, хоч і виглядає так: множимо точки на 1000 на місці, і
    # якби pyvista віддала масив спільним із вхідною сіткою, модель у самій
    # програмі тихо стала б міліметровою.
    out = out.copy()
    out.points = np.asarray(out.points, dtype=np.float64) * M_TO_MM
    # binary=True — за замовчуванням, але тут це не дрібниця: ASCII STL на
    # мільйон трикутників це 200+ МБ тексту й хвилини на самий лише запис.
    out.save(str(path), binary=True)
    return int(out.n_cells)


def _from_stl(path: Path) -> pv.PolyData:
    """Файл STL у міліметрах → сітка в метрах, зі зшитими вершинами."""
    mesh = pv.read(str(path))
    # `clean` без допуску зливає лише точно збіжні точки — саме те, що STL
    # роздублював при записі, і нічого зверху.
    mesh = mesh.clean()
    mesh.points = np.asarray(mesh.points, dtype=np.float64) / M_TO_MM
    return mesh


# --------------------------------------------------------------------------
# Сам виклик
# --------------------------------------------------------------------------

def _run(argv: list[str], say) -> str:
    """Проганяє процес, віддаючи рядки в `say` не частіше за _SAY_EVERY.

    Читання — через `iter(readline, "")`, як у `fs_backend.Runner`: перебір
    файлу по рядках буферизує наперед і живий поступ застигає.
    """
    proc = subprocess.Popen(
        argv, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        bufsize=1, universal_newlines=True, encoding="utf-8",
        errors="replace", creationflags=_NO_WINDOW)

    tail: list[str] = []
    last = 0.0
    for line in iter(proc.stdout.readline, ""):
        line = line.strip()
        if not line:
            continue
        # Хвіст лишаємо коротким: він потрібен лише щоб показати причину
        # відмови, а повний лог обгортання — це десятки тисяч рядків поступу.
        tail.append(line)
        if len(tail) > 40:
            del tail[0]
        now = time.monotonic()
        if now - last >= _SAY_EVERY:
            last = now
            say(line[:110])
    proc.stdout.close()
    code = proc.wait()
    text = "\n".join(tail)
    if code != 0:
        raise RuntimeError(
            f"wrapwrap відмовив (код {code}):" + "\n\n" + text[-600:] + "\n\n"
            "Найчастіше це замалий alpha на дуже дрібній деталі. Спробуйте "
            "більший alpha, або «Полагодити як слайсер».")
    return text


def repair(mesh: pv.PolyData, alpha: float, offset: float,
           say=None) -> pv.PolyData:
    """Обгорнена копія `mesh`. Сітка на вході й на виході — в метрах.

    `alpha` і `offset` — відносні числа `wrapwrap` (частки габариту, більше =
    точніше й значно повільніше), а не міліметри.

    Викликати з потоку: на реальній деталі це хвилини.
    """
    say = say or (lambda _text: None)
    if mesh is None or mesh.n_cells == 0:
        raise ValueError("Нема чого обгортати: у моделі жодного трикутника.")
    if alpha <= 0 or offset <= 0:
        raise ValueError("alpha й offset мусять бути додатні.")
    exe = exe_path()
    if exe is None:
        raise RuntimeError(why_not())

    work = Path(tempfile.mkdtemp(prefix="fs_alphawrap_"))
    src, dst = work / "in.stl", work / "out.stl"
    try:
        count = _to_stl(mesh, src)
        say(f"подаю {count} трикутників у alpha wrap (alpha={alpha:g})")
        _run([str(exe), "-i", str(src), "-alpha", f"{alpha:g}",
              "-offset", f"{offset:g}", "-o", str(dst)], say)
        if not dst.is_file():
            raise RuntimeError(
                "wrapwrap завершився без помилки, але файла не залишив.")
        say("читаю обгорнену модель і зшиваю вершини")
        out = _from_stl(dst)
    finally:
        shutil.rmtree(work, ignore_errors=True)

    if out.n_cells == 0:
        raise RuntimeError("Після обгортання не лишилося жодного трикутника.")
    return out


# --------------------------------------------------------------------------
# Переклад відносних чисел у міліметри — для вікна
# --------------------------------------------------------------------------

# Калібрування оцінки трикутників; звідки взялося — у estimate_triangles.
_TRI_K = 1.6


def _diagonal_m(mesh: pv.PolyData) -> float:
    b = mesh.bounds
    return float(np.linalg.norm([b[1] - b[0], b[3] - b[2], b[5] - b[4]]))


def absolute_mm(mesh_or_diagonal, relative: float) -> float:
    """Абсолютний розмір у мм, що відповідає відносному числу `wrapwrap`.

    Обидва його параметри — частки діагоналі габариту, тож абсолютне
    значення це діагональ поділити на число. Показувати людині треба саме
    його: «50» ні про що не каже, «0.35 мм» каже все.

    ДЛЯ OFFSET це точно — наскільку виросте тіло З КОЖНОГО БОКУ. Виміряно на
    кубі 10 мм (діагональ 17.32 мм), alpha=50:

        offset=50    габарит 10.700 мм    формула дає +0.693    похибка 1%
        offset=150   габарит 10.233 мм    формула дає +0.231    похибка 1%
        offset=300   габарит 10.116 мм    формула дає +0.115    похибка 1%

    ДЛЯ ALPHA це порядок роздільної здатности: при alpha=50 сторона
    трикутника вийшла близько 0.4 мм проти 0.35 мм за формулою. Точної
    рівности тут не буває — поверхня адаптивна.
    """
    if relative <= 0:
        return 0.0
    if isinstance(mesh_or_diagonal, (int, float)):
        diagonal_m = float(mesh_or_diagonal)
    else:
        diagonal_m = _diagonal_m(mesh_or_diagonal)
    return diagonal_m * M_TO_MM / relative


def relative_for_mm(mesh_or_diagonal, millimetres: float) -> float:
    """Відносне число `wrapwrap`, яке дає заданий розмір у міліметрах.

    Обернене до `absolute_mm`. Через нього вікно й працює: людина задає зазор
    і найдрібнішу деталь у міліметрах, а дільники рахуються тут — інакше
    напрямок неминуче читається навпаки, бо більше число дає менший розмір.
    """
    if millimetres <= 0:
        return 0.0
    if isinstance(mesh_or_diagonal, (int, float)):
        diagonal_m = float(mesh_or_diagonal)
    else:
        diagonal_m = _diagonal_m(mesh_or_diagonal)
    return diagonal_m * M_TO_MM / millimetres


def estimate_triangles(mesh: pv.PolyData, alpha: float) -> int:
    """Скільки приблизно трикутників дасть обгортання. 0 — не вгадати.

    Питання перед натиском завжди одне: чи не вилізе мільйон. Трикутників
    виходить площа поділити на квадрат роздільної здатности, тобто
    пропорційно `площа * (alpha / діагональ)²`; коефіцієнт калібрований на
    кубі 10 мм із дірою (площа 550 мм², діагональ 17.32 мм):

        alpha=50    7 324 трикутники   формула дає 7 320    (калібрування)
        alpha=500 696 648 трикутників  формула дає 732 000  похибка 5%

    Десятикратна перевірка — того досить, щоб попередити про порядок, і
    замало, щоб обіцяти точне число. Тому в вікні це «≈».
    """
    if alpha <= 0 or mesh is None or mesh.n_cells == 0:
        return 0
    diagonal_mm = _diagonal_m(mesh) * M_TO_MM
    if diagonal_mm <= 0:
        return 0
    area_mm2 = float(mesh.area) * M_TO_MM * M_TO_MM
    return int(_TRI_K * area_mm2 * (alpha / diagonal_mm) ** 2)


def ball_mm_for_triangles(mesh: pv.PolyData, target: int) -> float:
    """Радіус кулі, за якого вийде приблизно `target` трикутників. 0 — ніяк.

    Обернене до `estimate_triangles`: та сама формула, розвʼязана відносно
    розміру. Потрібне для дефолту у вікні, коли комірки сітки ще немає, —
    інакше єдиним орієнтиром лишається частка габариту, а вона на моделі в
    пів метра дає кулю в сантиметр.
    """
    if target <= 0 or mesh is None or mesh.n_cells == 0:
        return 0.0
    area_mm2 = float(mesh.area) * M_TO_MM * M_TO_MM
    if area_mm2 <= 0:
        return 0.0
    return float(np.sqrt(_TRI_K * area_mm2 / target))
